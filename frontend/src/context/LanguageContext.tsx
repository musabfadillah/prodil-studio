interface LanguageContextValue {
  language: LanguageCode;
  option: LanguageOption;
  setLanguage: (language: LanguageCode) => void;
  t: (key: string) => string;
  templateName: (id: number) => string;
  templateDescription: (id: number) => string;
  templateBadge: (id: number) => string;
  templateRole: (id: number) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    const saved = localStorage.getItem('prodil_lang') as LanguageCode | null;
    return LANGUAGES.some((item) => item.code === saved) ? saved! : 'id-ID';
  });

  const setLanguage = (next: LanguageCode) => {
    setLanguageState(next);
    localStorage.setItem('prodil_lang', next);
  };

  const value = useMemo(() => ({
    language,
    option: LANGUAGES.find((item) => item.code === language) || LANGUAGES[4],
    setLanguage,
    t: (key: string) =>
      workspaceTranslations[language][key]
      || componentUiTranslations[language][key]
      || inheritedUiTranslations[language][key]
      || dictionaries[language][key]
      || key,
    templateName: (id: number) => templateNames[language][Math.max(0, Math.min(14, id - 1))],
    templateDescription: (id: number) => templateDescriptions[language][Math.max(0, Math.min(14, id - 1))],
    templateBadge: (id: number) => templateBadges[language][Math.max(0, Math.min(14, id - 1))],
    templateRole: (id: number) => templateRoles[language][Math.max(0, Math.min(14, id - 1))],
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
};
